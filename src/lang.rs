//! Four-language UI text: 简体中文 (default) / English / 日本語 / 繁體中文.
//!
//! The Chinese string is used as the lookup key, so `tr(key, Lang::Zh)` returns
//! the key verbatim — every other language only needs the entries it actually
//! translates. Unknown keys fall back to the Chinese original, which keeps the
//! app readable even if a translation is missing.

/// Supported UI languages.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Zh,
    En,
    Ja,
    ZhTw,
}

impl Lang {
    /// All languages with their display names (for the settings dropdown).
    pub fn names() -> [(Lang, &'static str); 4] {
        [
            (Lang::Zh, "简体中文"),
            (Lang::En, "English"),
            (Lang::Ja, "日本語"),
            (Lang::ZhTw, "繁體中文"),
        ]
    }

    /// Stable id for persistence.
    pub fn id(self) -> &'static str {
        match self {
            Lang::Zh => "zh",
            Lang::En => "en",
            Lang::Ja => "ja",
            Lang::ZhTw => "zh-tw",
        }
    }

    /// Parse the persisted id back into a language.
    pub fn from_id(s: &str) -> Lang {
        match s {
            "en" => Lang::En,
            "ja" => Lang::Ja,
            "zh-tw" => Lang::ZhTw,
            _ => Lang::Zh,
        }
    }
}

