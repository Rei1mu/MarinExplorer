/// Translate `key` for `lang`. Chinese returns the key verbatim; other
/// languages fall back to Chinese when a translation is missing. `key` must be
/// `&'static str` (all our UI strings are literals) so the result is 'static.
pub fn tr(key: &'static str, lang: Lang) -> &'static str {
    match lang {
        Lang::Zh => key,
        Lang::En => lookup(key).map(|x| x.0).unwrap_or(key),
        Lang::Ja => lookup(key).map(|x| x.1).unwrap_or(key),
        Lang::ZhTw => lookup(key).map(|x| x.2).unwrap_or(key),
    }
}
